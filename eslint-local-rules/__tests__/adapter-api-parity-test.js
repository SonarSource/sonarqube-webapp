'use strict';

const path = require('path');

// ── fs mock setup ─────────────────────────────────────────────────────────────
// Mock fs BEFORE requiring the rule so the mock is in place at module init time.
const mockReadFileSync = jest.fn();
const mockExistsSync = jest.fn();
const mockStatSync = jest.fn();

jest.mock('fs', () => ({
  ...jest.requireActual('fs'),
  readFileSync: mockReadFileSync,
  existsSync: mockExistsSync,
  statSync: mockStatSync,
}));

const rule = require('../adapter-api-parity');

const { RuleTester } = require('eslint');

const repoRoot = path.resolve(__dirname, '../..');
const SQS_ADAPTERS = path.join(repoRoot, 'libs/sq-server-commons/src/sq-server-adapters');
const SQC_ADAPTERS = path.join(repoRoot, 'private/apps/sq-cloud/src/sq-cloud-adapters');

function sqsFile(rel) {
  return path.join(SQS_ADAPTERS, rel);
}
function sqcFile(rel) {
  return path.join(SQC_ADAPTERS, rel);
}
function sqcRelRoot(rel) {
  return `private/apps/sq-cloud/src/sq-cloud-adapters/${rel}`;
}
function sqsRelRoot(rel) {
  return `libs/sq-server-commons/src/sq-server-adapters/${rel}`;
}

const ruleTesterOptions = {
  languageOptions: {
    parser: require('@typescript-eslint/parser'),
    parserOptions: { ecmaFeatures: { jsx: true } },
  },
};

// ── Test lifecycle ────────────────────────────────────────────────────────────
// RuleTester calls jest describe/it internally, so beforeEach inside a wrapping
// describe block runs before each test case generated by ruleTester.run().
beforeEach(() => {
  jest.clearAllMocks();
  rule._counterpartCache.clear();
  // Default: no counterpart files exist, stat/reads throw
  mockExistsSync.mockReturnValue(false);
  mockStatSync.mockImplementation(() => {
    throw new Error('File not found (mock)');
  });
  mockReadFileSync.mockImplementation(() => {
    throw new Error('File not found (mock)');
  });
});

// ── Files outside adapter directories — no rule activation ───────────────────
describe('files outside adapter directories', () => {
  const tester = new RuleTester(ruleTesterOptions);
  tester.run('adapter-api-parity', rule, {
    valid: [
      {
        code: `export function foo() {}`,
        filename: path.join(repoRoot, 'libs/shared/src/helpers/misc.ts'),
      },
      {
        code: `export function foo() {}`,
        filename: path.join(repoRoot, 'apps/sq-server/src/foo.ts'),
      },
    ],
    invalid: [],
  });
});

// ── Skip __tests__ and __mocks__ directories ──────────────────────────────────
describe('skip test and mock directories inside adapter dirs', () => {
  const tester = new RuleTester(ruleTesterOptions);
  tester.run('adapter-api-parity', rule, {
    valid: [
      {
        code: `export function myTest() {}`,
        filename: sqsFile('helpers/__tests__/feature-flags-test.ts'),
      },
      {
        code: `export function myTest() {}`,
        filename: sqcFile('helpers/__tests__/feature-flags-test.ts'),
      },
      {
        code: `export const mock = {};`,
        filename: sqsFile('components/ui/__mocks__/SomeMock.ts'),
      },
    ],
    invalid: [],
  });
});

// ── Missing counterpart file ──────────────────────────────────────────────────
describe('missing counterpart file', () => {
  // existsSync returns false (default from beforeEach)
  const tester = new RuleTester(ruleTesterOptions);
  tester.run('adapter-api-parity', rule, {
    valid: [],
    invalid: [
      {
        code: `export function myAdapter() {}`,
        filename: sqsFile('helpers/new-adapter.ts'),
        errors: [
          {
            messageId: 'missingCounterpartFile',
            data: { counterpartPath: sqcRelRoot('helpers/new-adapter.ts') },
          },
        ],
      },
      {
        code: `export function myAdapter() {}`,
        filename: sqcFile('helpers/cloud-only-adapter.ts'),
        errors: [
          {
            messageId: 'missingCounterpartFile',
            data: { counterpartPath: sqsRelRoot('helpers/cloud-only-adapter.ts') },
          },
        ],
      },
    ],
  });
});

// ── Perfect parity — no errors ────────────────────────────────────────────────
describe('perfect parity', () => {
  beforeEach(() => {
    mockExistsSync.mockReturnValue(true);
    mockStatSync.mockReturnValue({ mtimeMs: 1000 });
  });

  describe('same single function export', () => {
    beforeEach(() => {
      mockReadFileSync.mockReturnValue(`export function useFlags() { return {}; }`);
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [
        {
          code: `export function useFlags() { return defaultFlags; }`,
          filename: sqsFile('helpers/feature-flags-parity.ts'),
        },
      ],
      invalid: [],
    });
  });

  describe('multiple matching exports', () => {
    beforeEach(() => {
      mockReadFileSync.mockReturnValue(`
        export function isSameBranchLike(a, b) { return a === b; }
        export function isMainBranch(branch) { return branch.isMain; }
      `);
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [
        {
          code: `
            export function isSameBranchLike(a, b) { return false; }
            export function isMainBranch(branch) { return false; }
          `,
          filename: sqsFile('helpers/branch-like-parity.ts'),
        },
      ],
      invalid: [],
    });
  });

  describe('type export parity', () => {
    describe('type declaration matched by type re-export specifier', () => {
      beforeEach(() => {
        // SQC re-exports a value and a type using `export { type Foo }` inline syntax
        mockExistsSync.mockReturnValue(true);
        mockStatSync.mockReturnValue({ mtimeMs: 1000 });
        mockReadFileSync.mockReturnValue(`
          export { useDashboardRuleLabels, type DashboardRuleLabelsEntity } from '../../hooks/useDashboardRuleLabels';
        `);
      });
      const tester = new RuleTester(ruleTesterOptions);
      tester.run('adapter-api-parity', rule, {
        valid: [
          {
            // SQS declares the type inline — `export type Foo = ...` matches `export { type Foo }`
            code: `
              export type DashboardRuleLabelsEntity = { type: 'PROJECT'; organization: string };
              export function useDashboardRuleLabels(args) {}
            `,
            filename: sqsFile('queries/widget-rule-metadata.ts'),
          },
        ],
        invalid: [],
      });
    });

    describe('type declaration matched by export type { Foo } form', () => {
      beforeEach(() => {
        // SQC uses `export type { Foo }` block form
        mockExistsSync.mockReturnValue(true);
        mockStatSync.mockReturnValue({ mtimeMs: 1000 });
        mockReadFileSync.mockReturnValue(`
          export type { DashboardRuleLabelsEntity } from '../../hooks/useDashboardRuleLabels';
          export { useDashboardRuleLabels } from '../../hooks/useDashboardRuleLabels';
        `);
      });
      const tester = new RuleTester(ruleTesterOptions);
      tester.run('adapter-api-parity', rule, {
        valid: [
          {
            code: `
              export type DashboardRuleLabelsEntity = { type: 'PROJECT'; organization: string };
              export function useDashboardRuleLabels(args) {}
            `,
            filename: sqsFile('queries/widget-rule-metadata2.ts'),
          },
        ],
        invalid: [],
      });
    });

    describe('type-only exports that have no counterpart are flagged', () => {
      beforeEach(() => {
        // SQC counterpart has only the value export, missing the type
        mockExistsSync.mockReturnValue(true);
        mockStatSync.mockReturnValue({ mtimeMs: 1000 });
        mockReadFileSync.mockReturnValue(`
          export { useDashboardRuleLabels } from '../../hooks/useDashboardRuleLabels';
        `);
      });
      const tester = new RuleTester(ruleTesterOptions);
      tester.run('adapter-api-parity', rule, {
        valid: [],
        invalid: [
          {
            code: `
              export type DashboardRuleLabelsEntity = { type: 'PROJECT'; organization: string };
              export function useDashboardRuleLabels(args) {}
            `,
            filename: sqsFile('queries/widget-rule-metadata3.ts'),
            errors: [{ messageId: 'missingExportInCounterpart' }],
          },
        ],
      });
    });
  });

  describe('value export here, type export in counterpart — kindMismatch', () => {
    beforeEach(() => {
      mockExistsSync.mockReturnValue(true);
      mockStatSync.mockReturnValue({ mtimeMs: 1000 });
      mockReadFileSync.mockReturnValue(`export type MyEntity = { id: string };`);
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [],
      invalid: [
        {
          code: `export const MyEntity = {};`,
          filename: sqsFile('queries/kind-mismatch-value-vs-type.ts'),
          errors: [
            {
              messageId: 'kindMismatch',
              data: {
                name: 'MyEntity',
                currentKind: 'value',
                counterpartKind: 'type',
                counterpartPath: sqcRelRoot('queries/kind-mismatch-value-vs-type.ts'),
              },
            },
          ],
        },
      ],
    });
  });

  describe('type export here, value export in counterpart — kindMismatch', () => {
    beforeEach(() => {
      mockExistsSync.mockReturnValue(true);
      mockStatSync.mockReturnValue({ mtimeMs: 1000 });
      mockReadFileSync.mockReturnValue(`export const MyEntity = {};`);
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [],
      invalid: [
        {
          code: `export type MyEntity = { id: string };`,
          filename: sqsFile('queries/kind-mismatch-type-vs-value.ts'),
          errors: [
            {
              messageId: 'kindMismatch',
              data: {
                name: 'MyEntity',
                currentKind: 'type',
                counterpartKind: 'value',
                counterpartPath: sqcRelRoot('queries/kind-mismatch-type-vs-value.ts'),
              },
            },
          ],
        },
      ],
    });
  });

  describe('both sides type-only — no kindMismatch', () => {
    beforeEach(() => {
      mockExistsSync.mockReturnValue(true);
      mockStatSync.mockReturnValue({ mtimeMs: 1000 });
      // SQC uses a type re-export specifier
      mockReadFileSync.mockReturnValue(`export { type MyEntity } from '../../types';`);
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [
        {
          // SQS uses a type declaration — both type-only, should be fine
          code: `export type MyEntity = { id: string };`,
          filename: sqsFile('queries/kind-match-both-type.ts'),
        },
      ],
      invalid: [],
    });
  });

  describe('non-function variable exports (createQueryHook pattern)', () => {
    beforeEach(() => {
      mockReadFileSync.mockReturnValue(
        `export const useMeasuresComponentQuery = createQueryHook((params) => options(params));`,
      );
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [
        {
          code: `export const useMeasuresComponentQuery = createQueryHook((p) => opts(p));`,
          filename: sqsFile('queries/measures-parity.ts'),
        },
      ],
      invalid: [],
    });
  });

  describe('matching re-export specifiers', () => {
    beforeEach(() => {
      mockReadFileSync.mockReturnValue(
        `export { ComponentContext } from '../../context/ComponentContext';`,
      );
    });
    const tester = new RuleTester(ruleTesterOptions);
    tester.run('adapter-api-parity', rule, {
      valid: [
        {
          code: `export { ComponentContext } from '../../context/componentContext/ComponentContext';`,
          filename: sqsFile('helpers/re-exports-parity.ts'),
        },
      ],
      invalid: [],
    });
  });
});

